function readMod(relPath) {
  let code = readFileSync(join(ROOT, relPath), 'utf8');
  // Strip local ESM imports and convert `export ` declarations into local bindings
  code = code.replace(/^\s*import\s+[\s\S]*?from\s+['"]\.\/[^'"]+['"];\s*$/gm, '');
  code = code.replace(/^export\s+(?=(?:async\s+)?(?:function|const|let|var|class)\b)/gm, '');
  return `// ── ${relPath} ──────────────────────────────────────────\n${code.trim()}\n`;
}

